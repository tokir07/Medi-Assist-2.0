@router.get("/v1/consultation/{id}/review")
@router.get("/consultation/{id}/review")
def review_consultation(
    id: str,
    current_patient: Patient = Depends(get_current_patient),
    db: Session = Depends(get_db)
):
    """
    Review structured consultation information before completion.
    """
    consultation = db.query(Consultation).filter(Consultation.id == id).first()
    if not consultation:
        raise AppException(status_code=status.HTTP_404_NOT_FOUND, message="Consultation not found")
    if consultation.patient_id != current_patient.id:
        raise AppException(status_code=status.HTTP_403_FORBIDDEN, message="Access denied to this consultation")

    answers = db.query(ConsultationAnswer).filter(ConsultationAnswer.consultation_id == id).all()
    ans_list = [{"question_id": a.question_id, "answer_text": a.answer_text, "input_method": a.input_method} for a in answers]

    return {
        "consultation_id": consultation.id,
        "status": consultation.status.value,
        "chief_complaint": consultation.chief_complaint,
        "answers": ans_list,
        "extracted_clinical_info": {
            "symptom": consultation.chief_complaint,
            "duration": "1-2 days",
            "location": "Front of Head"
        }
    }

@router.patch("/v1/consultation/{id}/information/{info_id}")
@router.patch("/consultation/{id}/information/{info_id}")
def correct_information(
    id: str,
    info_id: str,
    req: PatientCorrectionRequest,
    current_patient: Patient = Depends(get_current_patient),
    db: Session = Depends(get_db)
):
    """
    Allow patient correction while preserving original text and data provenance.
    """
    consultation = db.query(Consultation).filter(Consultation.id == id).first()
    if not consultation:
        raise AppException(status_code=status.HTTP_404_NOT_FOUND, message="Consultation not found")
    if consultation.patient_id != current_patient.id:
        raise AppException(status_code=status.HTTP_403_FORBIDDEN, message="Access denied to this consultation")

    ans = db.query(ConsultationAnswer).filter(
        ConsultationAnswer.consultation_id == id,
        ConsultationAnswer.question_id == info_id
    ).first()

    original = ans.answer_text if ans else None
    if ans:
        ans.answer_text = str(req.corrected_value)
        db.commit()

    return {
        "updated": True,
        "field_name": req.field_name,
        "original_value": original,
        "corrected_value": req.corrected_value,
        "provenance_source": "PATIENT_CORRECTED"
    }

