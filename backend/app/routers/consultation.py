@router.post("/v1/consultation")
@router.post("/consultation")
def start_consultation(
    req: StartConsultationRequest = StartConsultationRequest(),
    current_patient: Patient = Depends(get_current_patient),
    db: Session = Depends(get_db)
):
    """
    Start a new AI Pre-Consultation session for the authenticated patient.
    """
    consultation = consultation_service.start_consultation(current_patient.id, req.language or "en", db)
    return {
        "consultation_id": consultation.id,
        "status": consultation.status.value,
        "current_step": consultation.current_step
    }

@router.post("/v1/consultation/{id}/chief-complaint")
@router.post("/consultation/{id}/chief-complaint")
def submit_chief_complaint(
    id: str,
    req: ChiefComplaintRequest,
    current_patient: Patient = Depends(get_current_patient),
    db: Session = Depends(get_db)
):
    """
    Submit chief complaint choice and original patient text wording.
    """
    consultation = db.query(Consultation).filter(Consultation.id == id).first()
    if not consultation:
        raise AppException(status_code=status.HTTP_404_NOT_FOUND, message="Consultation not found")
    if consultation.patient_id != current_patient.id:
        raise AppException(status_code=status.HTTP_403_FORBIDDEN, message="Access denied to this consultation")

    q_model = consultation_service.set_chief_complaint(consultation, req.complaint, req.original_text, db)
    options = json.loads(q_model.options) if q_model.options else []
    return {
        "question_id": q_model.id,
        "question": q_model.question_text,
        "type": q_model.question_type,
        "options": options,
        "allow_voice": True
    }

